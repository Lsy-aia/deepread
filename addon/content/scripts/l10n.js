DeepRead.uiLang = function () {
  return String(Zotero.locale || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
};

DeepRead.t = function (key, args = {}) {
  const table = DeepRead.STRINGS[DeepRead.uiLang()] || DeepRead.STRINGS.en;
  const template = table[key] ?? DeepRead.STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (args[name] ?? `{${name}}`));
};

DeepRead.bilingual = function (zh, en) {
  return DeepRead.uiLang() === "zh" ? zh : en;
};
